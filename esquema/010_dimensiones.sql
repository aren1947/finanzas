-- Dimensiones: catálogos chicos. Las editás a mano o con un procedimiento (crear_categoria);
-- dim_persona, dim_comercio y dim_etiqueta las arma el ETL desde bronce.

create table dim_banco (
  id integer generated by default as identity primary key,
  nombre text unique not null
);

create table dim_tarjeta (
  id integer generated by default as identity primary key,
  nombre text unique not null,
  banco_id integer references dim_banco(id) deferrable initially deferred,
  cierre_dia integer,
  vence_dia integer,
  nombre_visible text
);

create table dim_categoria (
  id integer generated by default as identity primary key,
  nombre text unique not null,
  emoji text,
  tipo text not null default 'egreso'
);

create table dim_medio (
  id integer generated by default as identity primary key,
  nombre text unique not null
);

create table dim_persona (
  id integer generated by default as identity primary key,
  nombre text unique not null
);

create table dim_etiqueta (
  id integer generated by default as identity primary key,
  nombre text unique not null
);

create table dim_comercio (
  id integer generated by default as identity primary key,
  referencia text not null,
  cuotas_totales integer not null default 0,
  nombre text not null,
  emoji text,
  categoria_id integer references dim_categoria(id) deferrable initially deferred,
  unique (referencia, cuotas_totales)
);
