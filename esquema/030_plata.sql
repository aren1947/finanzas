-- Plata: bronce limpio y tipado (fechas date, montos número, ids de dimensiones). Solo la escribe el ETL.

create table plata_dolar (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_dolar(id) deferrable initially deferred,
  fecha date not null,
  valor double precision not null
);

create table plata_lineas_tarjeta (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_resumenes_lineas(id) deferrable initially deferred,
  tipo text not null check (tipo in ('compra', 'pago')),
  tarjeta text not null,
  fecha date not null,
  vencimiento date not null,
  referencia text not null,
  cuota_nro integer,
  cuota_total integer,
  comprobante text,
  monto_ars double precision not null default 0,
  monto_usd double precision not null default 0
);

create table plata_eventos (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_mensajes(id) deferrable initially deferred,
  fecha date not null,
  tipo text not null check (tipo in ('sueldo_bruto', 'pago_tarjeta')),
  monto_ars double precision not null,
  monto_usd double precision not null default 0,
  tipo_cambio double precision,
  retencion_pct double precision,
  descripcion text
);

create table plata_sueldo (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_sueldo(id) deferrable initially deferred,
  fecha_cobro date not null,
  bruto_ars double precision not null,
  retencion_pct double precision not null,
  retencion_ars double precision not null,
  neto_ars double precision not null
);

create table plata_gastos (
  id integer generated by default as identity primary key,
  origen text not null check (origen in ('bronce_gastos', 'bronce_compartidos')),
  bronce_id integer not null,
  fecha date not null,
  monto_ars double precision not null,
  monto_usd double precision not null default 0,
  moneda text not null check (moneda in ('ARS', 'USD')),
  tipo_cambio double precision,
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  medio_id integer not null references dim_medio(id) deferrable initially deferred,
  tarjeta_id integer references dim_tarjeta(id) deferrable initially deferred,
  cuotas integer not null default 1,
  descripcion text not null,
  etiqueta_id integer references dim_etiqueta(id) deferrable initially deferred,
  unique (origen, bronce_id)
);

create table plata_servicios (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_servicios(id) deferrable initially deferred,
  nombre text not null unique,
  monto double precision not null,
  moneda text not null check (moneda in ('ARS', 'USD')),
  frecuencia text not null default 'mensual',
  dia integer,
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  medio_id integer not null references dim_medio(id) deferrable initially deferred,
  tarjeta_id integer references dim_tarjeta(id) deferrable initially deferred,
  activa integer not null default 1
);

create table plata_pagos (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_pagos(id) deferrable initially deferred,
  clave text not null unique,
  fecha date not null,
  tipo text not null check (tipo in ('resumen', 'servicio')),
  mes text not null,
  tarjeta_id integer references dim_tarjeta(id) deferrable initially deferred,
  servicio_id integer references plata_servicios(id) deferrable initially deferred,
  monto_ars double precision not null,
  monto_usd double precision not null default 0,
  moneda text not null check (moneda in ('ARS', 'USD')),
  tipo_cambio double precision
);

create table plata_precios_fijo (
  id integer generated by default as identity primary key,
  servicio_id integer not null references plata_servicios(id) deferrable initially deferred,
  bronce_id integer references bronce_pagos(id) deferrable initially deferred,
  monto double precision not null,
  moneda text not null check (moneda in ('ARS', 'USD')),
  desde text not null,
  tipo_cambio double precision,
  unique (servicio_id, desde)
);

create table plata_deudas (
  id integer generated by default as identity primary key,
  origen text not null check (origen in ('bronce_deudas', 'bronce_compartidos')),
  bronce_id integer not null,
  fecha date not null,
  persona_id integer not null references dim_persona(id) deferrable initially deferred,
  concepto text not null,
  monto double precision not null,
  moneda text not null check (moneda in ('ARS', 'USD')),
  sentido text not null check (sentido in ('le_debo', 'me_deben')),
  unique (origen, bronce_id)
);

create table plata_saldos_deuda (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_saldos_deuda(id) deferrable initially deferred,
  deuda_id integer not null unique references plata_deudas(id) deferrable initially deferred,
  fecha date not null
);

create table plata_pagos_deuda (
  id integer generated by default as identity primary key,
  bronce_id integer not null unique references bronce_pagos_deuda(id) deferrable initially deferred,
  deuda_id integer not null references plata_deudas(id) deferrable initially deferred,
  fecha date not null,
  monto double precision not null check (monto > 0)
);

create table plata_compensaciones_deuda (
  id integer generated by default as identity primary key,
  bronce_id integer not null references bronce_compensaciones(id) deferrable initially deferred,
  deuda_id integer not null references plata_deudas(id) deferrable initially deferred,
  fecha date not null,
  monto double precision not null check (monto > 0),
  moneda text not null check (moneda in ('ARS', 'USD')),
  tipo_cambio double precision,
  unique (bronce_id, deuda_id)
);

-- el dólar vigente a una fecha (el último cargado hasta ese día)
create or replace function dolar_a(f date) returns double precision language sql stable as $$
  select d.valor from plata_dolar d where d.fecha <= f order by d.fecha desc, d.id desc limit 1
$$;

-- el último dólar cargado
create or replace function dolar_ultimo() returns double precision language sql stable as $$
  select d.valor from plata_dolar d order by d.fecha desc, d.id desc limit 1
$$;
