-- Bronce: lo que entra, tal cual llegó (texto). Solo se agrega y, para corregir un dato, se actualiza su fila.
-- Nunca se escribe en plata ni en oro: los arma el ETL (etl/).

create table bronce_mensajes (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  texto_crudo text not null
);

create table bronce_resumenes_lineas (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  tarjeta text not null,
  vencimiento text,
  fecha_texto text,
  referencia text,
  cuota text,
  comprobante text,
  pesos_texto text,
  dolares_texto text,
  texto_crudo text
);

create table bronce_sueldo (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  bronce_mensaje_id integer references bronce_mensajes(id) deferrable initially deferred,
  fecha_cobro_texto text,
  bruto_texto text,
  retencion_texto text,
  neto_texto text,
  texto_crudo text
);

create table bronce_gastos (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text, monto text, moneda text, descripcion text, categoria text, medio text, tarjeta text, cuotas text,
  texto_crudo text, primer_mes text, cotizacion double precision, etiqueta text
);

create table bronce_pagos (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text, monto text, moneda text, tipo text, tarjeta text, servicio text, mes text, texto_crudo text
);

create table bronce_servicios (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  nombre text, monto text, moneda text, frecuencia text, dia text, categoria text, medio text, tarjeta text,
  texto_crudo text, desde text, cotizacion double precision
);

create table bronce_deudas (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text, persona text, concepto text, monto text, moneda text, sentido text, texto_crudo text
);

create table bronce_saldos_deuda (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  deuda_id text, fecha text, texto_crudo text
);

create table bronce_pagos_deuda (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  deuda_id integer not null,
  fecha text not null,
  monto double precision not null check (monto > 0)
);

create table bronce_compensaciones (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text not null,
  deuda_id integer not null,
  contra_deuda_id integer not null,
  monto double precision not null,
  moneda text not null check (moneda in ('ARS', 'USD'))
);

create table bronce_dolar (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text, valor text, texto_crudo text
);

create table bronce_nombres_compra (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  referencia text, cuotas_totales text, nombre text, emoji text, texto_crudo text
);

create table bronce_presupuestos (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  categoria text not null,
  monto double precision not null check (monto >= 0),
  desde text not null check (desde ~ '^[0-9]{4}-[0-9]{2}$')
);

create table bronce_compartidos (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  fecha text not null,
  persona text not null,
  descripcion text not null,
  categoria text not null,
  total double precision not null check (total > 0),
  pago text not null check (pago in ('yo', 'otro')),
  mi_parte double precision not null check (mi_parte >= 0),
  medio text not null,
  check (mi_parte <= total)
);

create table bronce_previstos (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  periodo text not null check (periodo ~ '^[0-9]{4}-[0-1][0-9]$'),
  descripcion text not null check (length(trim(descripcion)) > 0),
  monto double precision not null check (monto > 0),
  categoria text
);

create table bronce_previstos_cambios (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  previsto_id integer not null references bronce_previstos(id) deferrable initially deferred,
  accion text not null check (accion in ('postergar', 'confirmar', 'descartar')),
  periodo text check (periodo is null or periodo ~ '^[0-9]{4}-[0-1][0-9]$'),
  check ((accion = 'postergar') = (periodo is not null))
);

create table bronce_ahorro_metas (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  nombre text not null check (length(trim(nombre)) > 0),
  monto double precision not null check (monto >= 0),
  moneda text not null default 'ARS' check (moneda in ('ARS', 'USD')),
  para text check (para is null or para ~ '^[0-9]{4}-[0-1][0-9]$'),
  ya_tengo double precision not null default 0 check (ya_tengo >= 0),
  check (monto = 0 or para is not null)
);

create table bronce_ahorro_minimo (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  monto double precision not null check (monto >= 0),
  desde text not null default mes_actual() check (desde ~ '^[0-9]{4}-[0-1][0-9]$')
);

-- correcciones de una compra de un resumen ya pagado (su FK a oro_resumen_items se agrega en 040_oro.sql)
create table bronce_correcciones_resumen (
  id integer generated by default as identity primary key,
  cargado_en timestamptz not null default now(),
  origen text not null,
  item_id integer not null,
  fecha text, monto double precision, descripcion text, categoria text
);

-- metas viejas (antes de bronce_ahorro_metas); se conservan
create table metas (
  id integer generated by default as identity primary key,
  nombre text not null,
  monto_objetivo double precision,
  monto_acumulado double precision default 0,
  fecha_objetivo text,
  activa integer default 1
);
