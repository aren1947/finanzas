-- Oro: los hechos de los que salen los resúmenes y el tablero. Solo los escribe el ETL.

create table oro_hechos_tarjeta (
  id integer generated by default as identity primary key,
  plata_id integer not null unique references plata_lineas_tarjeta(id) deferrable initially deferred,
  tarjeta_id integer not null references dim_tarjeta(id) deferrable initially deferred,
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  fecha date not null,
  vencimiento date not null,
  tipo text not null,
  descripcion text not null,
  cuota_nro integer,
  cuota_total integer,
  monto_ars double precision not null,
  monto_usd double precision not null
);

create table oro_compromisos_tarjeta (
  id integer generated by default as identity primary key,
  plata_gasto_id integer not null references plata_gastos(id) deferrable initially deferred,
  tarjeta_id integer not null references dim_tarjeta(id) deferrable initially deferred,
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  descripcion text not null,
  cuota_nro integer not null,
  cuota_total integer not null,
  periodo text not null,
  monto_ars double precision not null,
  monto_usd double precision not null,
  unique (plata_gasto_id, cuota_nro)
);

-- foto de las compras de cada resumen pagado: se agrega al pagarlo y no se recalcula
create table oro_resumen_items (
  id integer generated by default as identity primary key,
  plata_pago_id integer not null references plata_pagos(id) deferrable initially deferred,
  tarjeta_id integer not null references dim_tarjeta(id) deferrable initially deferred,
  periodo text not null,
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  descripcion text not null,
  monto_ars double precision not null,
  unique (plata_pago_id, descripcion)
);

alter table bronce_correcciones_resumen
  add foreign key (item_id) references oro_resumen_items(id) deferrable initially deferred;

create table oro_movimientos (
  id integer generated by default as identity primary key,
  origen_tabla text not null,
  origen_id integer not null,
  fecha date not null,
  tipo text not null check (tipo in ('ingreso', 'gasto')),
  categoria_id integer not null references dim_categoria(id) deferrable initially deferred,
  tarjeta_id integer references dim_tarjeta(id) deferrable initially deferred,
  descripcion text not null,
  monto_ars double precision not null,
  unique (origen_tabla, origen_id)
);
